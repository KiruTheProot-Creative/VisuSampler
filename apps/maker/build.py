import glob,os
d=os.path.dirname(os.path.abspath(__file__))
def r(f): return open(os.path.join(d,'src',f),encoding='utf8').read()
CORE='../../packages/core/src/index.js'
imports='''import {
  resample,stretchCh,stretchAll,granularRender,wavetableRender,uniVoices,smDefaults,smOf,hash01,hann,MODES as CORE_MODES,
  detectTransients as coreDetectTransients,zoneData as coreZoneData,zoneInterp as coreZoneInterp,zoneRatio as coreZoneRatio,
  crc32,encodePCM,decodePCM,Pack,writeVsamp,readVsamp,verifyVsamp,fmtBytes,bytesPer,
  estimate as coreEstimate,chooseStep,zoneBakeReason as coreZoneBakeReason,buildExportSet as coreBuildExportSet
} from '%s';
''' % CORE
parts=sorted(glob.glob(os.path.join(d,'src','parts','p*.js')))
js='\n'.join(open(p,encoding='utf8').read() for p in parts)
# the engine's AudioWorklet (engine.js + worklet.js, no imports) goes into app.js as text, loaded from a blob at run time
import json,re
EW=os.path.join(d,'..','..','packages','engine-wasm','src')
eng=open(os.path.join(EW,'engine.js'),encoding='utf8').read().replace('export function','function').replace('export async function','async function')
wk=re.sub(r"^import .*$",'',open(os.path.join(EW,'worklet.js'),encoding='utf8').read(),flags=re.M)
assert "/*@@WORKLET@@*/''" in js
js=js.replace("/*@@WORKLET@@*/''",json.dumps(eng+'\n'+wk))
app=imports+"(function(){\n'use strict';\n"+js+"\n})();\n"
open(os.path.join(d,'app.js'),'w',encoding='utf8').write(app)
css=r('style.css')+'\n'+r('style-extra.css')+'\n'+r('style-unity.css')
head=r('head.html').replace('/*@@CSS@@*/',css)
html='<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">\n'+head+'</head><body>\n'+r('body.html')+'\n<script type="module" src="app.js"></script>\n</body></html>\n'
open(os.path.join(d,'index.html'),'w',encoding='utf8').write(html)
print('built app.js',len(app),'index.html',len(html))

# ---- interface runtime for the VST window (same drawing code as the Designer) ----
RT_PARTS=['p000-prelude.js','p010-state.js','p020-tokens.js','p030-assets-mipmaps.js','p040-factories.js','p050-geometry-light.js',
          'p060-rendering-of-elements.js','p065-render-new.js','p066-graph.js','p100-tags-change-audio.js','p110-test-interaction.js','p200-events.js']
rt="/* generated by apps/maker/build.py from apps/maker/src: do not edit */\n(function(){\n'use strict';\n"
rt+='\n'.join(open(os.path.join(d,'src','parts',p),encoding='utf8').read() for p in RT_PARTS)
rt+='\n'+r('runtime/post.js')+'\n})();\n'
ui=os.path.join(d,'..','plugin','ui')
open(os.path.join(ui,'runtime.js'),'w',encoding='utf8').write(rt)
fonts=''.join("@font-face{font-family:'%s';src:url('fonts/%s.ttf');font-weight:100 900;}\n"%(fam,fn) for fam,fn in [('Figtree','Figtree'),('Unbounded','Unbounded'),('JetBrains Mono','JetBrainsMono'),('Pacifico','Pacifico'),('VT323','VT323')])
open(os.path.join(ui,'runtime.css'),'w',encoding='utf8').write('/* generated by apps/maker/build.py: do not edit */\n'+fonts+r('style.css')+'\n'+r('style-extra.css')+'\n'+r('style-unity.css'))
print('built plugin interface runtime',len(rt))
