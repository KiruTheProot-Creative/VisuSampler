// The NodeFX module catalogue (FXT in src/parts p300 / p305: every effect, its ports and settings) as data for
// HyperSynth's FX tab: apps/plugin/hypersynth/ui/fxcatalog.js. Run by build.py, so a module added to NodeFX / the
// Maker reaches HyperSynth too. Only the catalogue is taken (no editor code).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const d=path.dirname(fileURLToPath(import.meta.url)),parts=path.join(d,'..','src','parts');
const src=['p300-fx-model.js','p302-fx-mod-sources.js','p305-fx-catalog.js'].map(f=>fs.readFileSync(path.join(parts,f),'utf8')).join('\n');
const ctx={performance,Math,JSON,Object,Array,Number,String,console,S:{sig:[4,4],bpm:120,tags:[],fx:{graphs:{},scope:'master'}},
  clamp:(v,a,b)=>Math.max(a,Math.min(b,v)),hash01:()=>0,tagById:()=>null,nid:p=>p+Math.random().toString(36).slice(2,8),esc:s=>s,$:()=>null,$$:()=>[]};
vm.createContext(ctx);
vm.runInContext(src+'\n;this.__out={FXT,FX_CATS};',ctx,{filename:'fx-catalog'});
const {FXT,FX_CATS}=ctx.__out;
const keep=['label','kind','cat','ins','outs','lat','hint','fbOk'],pk=['k','label','min','max','unit','def','old','opts','log','sync','step'];
const cat={};
for(const [type,t] of Object.entries(FXT)){const o={};keep.forEach(k=>{if(t[k]!=null)o[k]=t[k];});
  o.params=(t.params||[]).map(q=>{const r={};pk.forEach(k=>{if(q[k]!=null)r[k]=q[k];});return r;});cat[type]=o;}
const out=path.join(d,'..','..','plugin','hypersynth','ui','fxcatalog.js');
fs.writeFileSync(out,'/* generated by apps/maker/tools/fx-catalog.mjs from the NodeFX catalogue (apps/maker/src/parts): do not edit */\nwindow.FXCAT='+JSON.stringify({cats:FX_CATS,types:cat})+';\n');
console.log('fxcatalog.js:',Object.keys(cat).length,'modules');
